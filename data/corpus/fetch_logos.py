#!/usr/bin/env python3
"""
Fetch each entity's site icon for the AI Intelligence Graph's cards.

For every entity in src/data/aiOntologyData.ts with an http website, it asks
Google's favicon service (no key, no cost) for the site's icon at 128 px and
saves it as public/ai/logos/<id>.png. Sites with no icon come back as Google's
generic globe, which is recognised by its bytes and skipped. The result is a
manifest, src/data/aiLogos.ts, listing the ids that have an icon.

Run: python3 fetch_logos.py [--only id,id] [--refresh]
Idempotent: an icon already on disk is kept unless --refresh is given.
"""
import hashlib, json, os, re, sys, time, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
DATA = os.path.join(ROOT, "src", "data", "aiOntologyData.ts")
OUT = os.path.join(ROOT, "public", "ai", "logos")
MANIFEST = os.path.join(ROOT, "src", "data", "aiLogos.ts")
UA = "Mozilla/5.0 (Macintosh) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36"
# Google's generic globe (what it returns when a site has no icon), by size and hash of the bytes.
GENERIC = set()


def nodes():
    t = open(DATA, encoding="utf8").read()
    s = t.index("[", t.index("=", t.index("export const AI_NODES")))
    e = t.index("\n];", s)
    return [json.loads(l.strip().rstrip(",")) for l in t[s + 1 : e].split("\n") if l.strip().startswith("{")]


def domain(url):
    m = re.match(r"^https?://([^/]+)", url.strip())
    return m.group(1).lower() if m else None


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=20) as r:
        return r.read()


TOPIC_TYPES = {"investor", "government", "vertical", "institution", "dataset", "benchmark"}


def is_company(n, domains_by_type):
    """A site icon belongs on a company or product, not on a topic that only cites a company's site."""
    name = n["name"]
    if re.search(r"capital stack|circular|super-cycle|\bgap\b|labor|litigation|restructuring|sovereign|v\. ", name, re.I):
        return False
    if name.count(" / ") >= 2 and not n.get("ticker"):  # a bundle of companies: one icon would mislead
        return False
    d = domain(n.get("website") or "")
    listed = bool(n.get("ticker")) and n["ticker"] not in ("private", "nonprofit")
    # A topic node (no ticker) reusing a real company's site: "AI-native consumer hardware" on openai.com.
    if n["type"] in TOPIC_TYPES and not listed and d and any(t != n["type"] for t in domains_by_type.get(d, set())):
        return False
    return True


def main():
    only = None
    if "--only" in sys.argv:
        only = set(sys.argv[sys.argv.index("--only") + 1].split(","))
    refresh = "--refresh" in sys.argv
    os.makedirs(OUT, exist_ok=True)
    # Learn the generic icon from a domain that certainly has none.
    try:
        GENERIC.add(hashlib.sha1(fetch("https://www.google.com/s2/favicons?domain=nonexistent-domain-xyz-123.invalid&sz=128")).hexdigest())
    except Exception as e:  # noqa: BLE001
        print("could not learn the generic icon:", e)
    have, skipped, failed, excluded = [], [], [], []
    ns = nodes()
    domains_by_type = {}
    for n in ns:
        d = domain(n.get("website") or "")
        if d:
            domains_by_type.setdefault(d, set()).add(n["type"])
    for n in ns:
        if only and n["id"] not in only:
            continue
        d = domain(n.get("website") or "")
        if not d:
            continue
        if not is_company(n, domains_by_type):
            excluded.append(n["id"])
            stale = os.path.join(OUT, n["id"] + ".png")
            if os.path.exists(stale):
                os.remove(stale)
            continue
        path = os.path.join(OUT, n["id"] + ".png")
        if os.path.exists(path) and not refresh:
            have.append(n["id"])
            continue
        try:
            b = fetch(f"https://www.google.com/s2/favicons?domain={d}&sz=128")
            if hashlib.sha1(b).hexdigest() in GENERIC or len(b) < 200:
                skipped.append((n["id"], d))
                continue
            open(path, "wb").write(b)
            have.append(n["id"])
            time.sleep(0.15)
        except Exception as e:  # noqa: BLE001
            failed.append((n["id"], d, str(e)[:60]))
    ids = sorted(set(have) | {f[:-4] for f in os.listdir(OUT) if f.endswith(".png")})
    open(MANIFEST, "w", encoding="utf8").write(
        "// AUTO-GENERATED by data/corpus/fetch_logos.py. Entity ids with a site icon in public/ai/logos/. Do not edit by hand.\n"
        "export const AI_LOGO_IDS: ReadonlySet<string> = new Set(" + json.dumps(ids) + ");\n"
        'export const logoUrl = (id: string): string | null => (AI_LOGO_IDS.has(id) ? `/ai/logos/${id}.png` : null);\n'
    )
    print(f"icons: {len(ids)}  generic/skipped: {len(skipped)}  failed: {len(failed)}  excluded topics: {len(excluded)}")
    if excluded:
        print("excluded:", ", ".join(excluded))
    if skipped:
        print("skipped:", ", ".join(f"{i} ({d})" for i, d in skipped[:40]))
    if failed:
        print("failed:", failed[:20])


if __name__ == "__main__":
    main()
