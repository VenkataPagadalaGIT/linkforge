#!/usr/bin/env python3
"""
Generate src/data/aiOntologyData.ts from ontology.entity and ontology.relation.

The output keeps the exact shape and key order of the hand-generated file, so
the first run after seeding reproduces it byte for byte (--check proves it).
Rows added later come after the seeded ones, in slug order.

Run: python3 gen_ontology_ts.py [--check]
"""
import json, os, subprocess, sys
sys.path.insert(0, os.path.dirname(__file__))
from db import CONTAINER, DB, USER

HERE = os.path.dirname(os.path.abspath(__file__))
DEST = os.path.join(HERE, "..", "..", "src", "data", "aiOntologyData.ts")
HEADER = ("// AUTO-GENERATED — AI Systems Map ontology (research + 10 personas, deduped, edge-reviewed). Do not edit by hand.\n"
          "// Generated by data/corpus/gen_ontology_ts.py from the ontology schema in research_corpus.\n"
          'import type { AiNode, AiEdge } from "./aiOntology";\n\n')
LEGACY_HEADER = ("// AUTO-GENERATED — AI Systems Map ontology (research + 10 personas, deduped, edge-reviewed). Do not edit by hand.\n"
                 'import type { AiNode, AiEdge } from "./aiOntology";\n\n')


def rows(q):
    """One JSON document per query, read whole: db.query splits on tabs and
    newlines, which json_agg output contains."""
    p = subprocess.run(["docker", "exec", "-i", CONTAINER, "psql", "-U", USER, "-d", DB, "-t", "-A", "-c",
                        "SELECT COALESCE(jsonb_agg(t), '[]'::jsonb)::text FROM (" + q + ") t"],
                       capture_output=True, text=True)
    if p.returncode != 0:
        raise SystemExit("QUERY FAILED:\n" + p.stderr[-2000:])
    return json.loads(p.stdout.strip() or "[]")


ents = rows("""
  SELECT slug, name, type, layer, tagline, story, hq, ticker, website, github, chokepoint, key_facts, related_update_ids
  FROM ontology.entity
  WHERE lifecycle <> 'defunct'
  ORDER BY seed_order NULLS LAST, slug""")
rels = rows("""
  SELECT f.slug AS "from", t.slug AS "to", r.relation, r.note
  FROM ontology.relation r JOIN ontology.entity f ON f.id = r.from_id JOIN ontology.entity t ON t.id = r.to_id
  WHERE r.verification <> 'superseded' AND (r.valid_to IS NULL OR r.valid_to >= current_date)
  ORDER BY r.seed_order NULLS LAST, f.slug, t.slug, r.relation""")


def node(e):
    o = {"id": e["slug"], "name": e["name"], "type": e["type"], "layer": e["layer"], "tagline": e["tagline"], "story": e["story"]}
    for k in ("hq", "ticker", "website", "github"):
        if e.get(k) is not None:
            o[k] = e[k]
    if e.get("chokepoint"):
        o["chokepoint"] = True
    if e.get("key_facts") is not None:
        o["keyFacts"] = e["key_facts"]
    if e.get("related_update_ids") is not None:
        o["relatedUpdateIds"] = e["related_update_ids"]
    return o


def edge(r):
    o = {"from": r["from"], "to": r["to"], "relation": r["relation"]}
    if r.get("note") is not None:
        o["note"] = r["note"]
    return o


def emit(o):
    return json.dumps(o, ensure_ascii=False, separators=(", ", ": "))


body = ("export const AI_NODES: AiNode[] = [\n" + "".join("  " + emit(node(e)) + ",\n" for e in ents) + "];\n\n"
        "export const AI_EDGES: AiEdge[] = [\n" + "".join("  " + emit(edge(r)) + ",\n" for r in rels) + "];\n")

if "--check" in sys.argv:
    current = open(DEST, encoding="utf8").read()
    same = current in (LEGACY_HEADER + body, HEADER + body)
    print(f"entities={len(ents)} relations={len(rels)} byte-identical-to-current={same}")
    if not same:
        a, b = current, LEGACY_HEADER + body
        k = next((i for i in range(min(len(a), len(b))) if a[i] != b[i]), min(len(a), len(b)))
        print("first difference at", k, repr(a[k - 80:k + 80]), "\nvs", repr(b[k - 80:k + 80]))
        raise SystemExit(1)
else:
    open(DEST, "w", encoding="utf8").write(HEADER + body)
    print(f"wrote {DEST}: entities={len(ents)} relations={len(rels)}")
