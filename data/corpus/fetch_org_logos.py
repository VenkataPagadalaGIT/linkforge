#!/usr/bin/env python3
"""
Favicons for organizations that are not graph entities (investors, law firms,
banks, the company's own hosts), for the chips and tables of the 360 file.
Each domain is verified first: the site's <title> must contain the name, so a
wrong domain never puts another company's mark next to a name. Icons come
from Google's s2 favicon service into public/ai/logos/orgs/<slug>.png; a
generic placeholder icon is skipped.

Run: python3 fetch_org_logos.py
"""
import hashlib, html, json, os, re, sys, time, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "public", "ai", "logos", "orgs")
SRC = os.path.join(HERE, "ontology", "org_domains.json")
UA = "mono-mind-ai-graph (organization icons; contact via venkatapagadala.com)"


def fetch(url, timeout=30):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=timeout) as r:
        return r.read()


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def main():
    orgs = json.load(open(SRC, encoding="utf8"))["orgs"]
    os.makedirs(OUT, exist_ok=True)
    try:  # the service used to answer a placeholder icon for unknown domains; now it answers 404, which the per-domain fetch already handles
        generic = hashlib.sha1(fetch("https://www.google.com/s2/favicons?domain=nonexistent-domain-xyz-123.invalid&sz=128")).hexdigest()
    except Exception:  # noqa: BLE001
        generic = None
    index, ok, skipped = {}, 0, []
    for o in orgs:
        s = slug(o["name"])
        path = os.path.join(OUT, f"{s}.png")
        if os.path.exists(path):
            index[o["name"]] = f"/ai/logos/orgs/{s}.png"
            continue
        try:
            page = fetch("https://" + o["domain"] + "/").decode("utf8", "replace")
            title = html.unescape(re.search(r"<title[^>]*>(.*?)</title>", page, re.S | re.I).group(1)).strip() if re.search(r"<title", page, re.I) else ""
            words = [w for w in re.split(r"\W+", o.get("match", o["name"]).lower()) if len(w) > 2]
            if not any(w in title.lower() or w in page[:4000].lower() for w in words):
                skipped.append(f"{o['name']} (title: {title[:40]!r})")
                continue
            b = fetch(f"https://www.google.com/s2/favicons?domain={o['domain']}&sz=128")
            if hashlib.sha1(b).hexdigest() == generic or len(b) < 200:
                skipped.append(f"{o['name']} (no icon)")
                continue
            open(path, "wb").write(b)
            index[o["name"]] = f"/ai/logos/orgs/{s}.png"
            ok += 1
        except Exception as e:  # noqa: BLE001
            skipped.append(f"{o['name']} ({str(e)[:40]})")
        time.sleep(0.4)
    json.dump(index, open(os.path.join(OUT, "index.json"), "w", encoding="utf8"), ensure_ascii=False, indent=1, sort_keys=True)
    ts = os.path.join(HERE, "..", "..", "src", "data", "aiOrgLogos.ts")
    open(ts, "w", encoding="utf8").write(
        "// AUTO-GENERATED by data/corpus/fetch_org_logos.py. Icons of organizations named in the 360 files (investors, counsel,\n"
        "// banks, the company's own hosts), each verified against the organization's own site. Do not edit by hand.\n"
        "export const AI_ORG_LOGOS: Record<string, string> = " + json.dumps(index, ensure_ascii=False, indent=1, sort_keys=True) + ";\n\n"
        "const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, \" \").trim();\n"
        "const BY_NORM: Record<string, string> = Object.fromEntries(Object.entries(AI_ORG_LOGOS).map(([k, v]) => [norm(k), v]));\n"
        "/** The icon for an organization name as the 360 files write it, or null. */\n"
        "export function orgLogo(name: string | null | undefined): string | null {\n"
        "  if (!name) return null;\n"
        "  return AI_ORG_LOGOS[name] ?? BY_NORM[norm(name)] ?? null;\n"
        "}\n")
    print(f"icons: {len(index)} (new {ok}); skipped {len(skipped)}: " + "; ".join(skipped))


if __name__ == "__main__":
    main()
