#!/usr/bin/env python3
"""export_hero_media.py: the living home portrait's media.

Usage: python3 scripts/hero/export_hero_media.py [source_dir]
       (default source_dir: ~/Desktop/Videos/Hero)

Sources, made with the Higgsfield connector on 2026-10-23 from the owner's own
photo (public/venkata-pagadala.jpeg) and approved by him:
  living-kling4-c1d29ffe.mp4      Kling 4.0, start and end frame = the photo:
                                  breathing, blinks, a warm smile; loops seamlessly
  transform-kling4-cd69d63d.mp4   Kling 4.0, start = the photo, end = the 2040
                                  picture: a cyan scan line sweeps left to right
                                  and turns the blazer into 2040 techwear
The alternates (alt-*) are kept in the same folder, unused.

Writes to public/hero/:
  venkata-pagadala-living.{webm,mp4}   720x720, no audio
  venkata-pagadala-2040.{webm,mp4}     720x720, no audio
  venkata-pagadala-2040.jpg            the transformation's last frame, 800x800:
                                       the particles sample their 2040 colours from it
and src/data/heroPortrait.ts with the URLs (each with ?v=<md5[:8]>, because
/public files are cached for a day) and the scan line's position over time,
measured frame by frame, so the dust rim recolours exactly where the line is.
"""
import hashlib, json, subprocess, sys, tempfile
from pathlib import Path
from PIL import Image

REPO = Path(__file__).resolve().parents[2]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "Desktop/Videos/Hero"
OUT = REPO / "public/hero"
WEB = "/hero"
LIVING = SRC / "living-kling4-c1d29ffe.mp4"
TRANSFORM = SRC / "transform-kling4-cd69d63d.mp4"
SIZE = 720


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def v(p: Path) -> str:
    return hashlib.md5(p.read_bytes()).hexdigest()[:8]


def encode(src: Path, stem: str) -> dict:
    webm, mp4 = OUT / f"{stem}.webm", OUT / f"{stem}.mp4"
    scale = f"scale={SIZE}:{SIZE}:flags=lanczos"
    run("ffmpeg", "-nostdin", "-y", "-v", "error", "-i", str(src), "-an", "-vf", scale, "-c:v", "libvpx-vp9",
        "-b:v", "0", "-crf", "36", "-row-mt", "1", "-deadline", "good", "-cpu-used", "2", "-pix_fmt", "yuv420p", str(webm))
    run("ffmpeg", "-nostdin", "-y", "-v", "error", "-i", str(src), "-an", "-vf", scale, "-c:v", "libx264", "-preset", "slow",
        "-crf", "26", "-profile:v", "high", "-pix_fmt", "yuv420p", "-movflags", "+faststart", str(mp4))
    dur = float(run("ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(mp4)))
    return {"webm": f"{WEB}/{webm.name}?v={v(webm)}", "mp4": f"{WEB}/{mp4.name}?v={v(mp4)}", "duration": round(dur, 3),
            "kb": {"webm": round(webm.stat().st_size / 1024), "mp4": round(mp4.stat().st_size / 1024)}}


def sweep(src: Path) -> list:
    """[seconds, x] pairs: x is the scan line's centre in -0.5..0.5 portrait units, while it is on screen."""
    pts = []
    with tempfile.TemporaryDirectory() as tmp:
        run("ffmpeg", "-nostdin", "-v", "error", "-i", str(src), "-vf", "fps=24,scale=180:180", f"{tmp}/f%04d.png")
        frames = sorted(Path(tmp).glob("f*.png"))
        for i, f in enumerate(frames):
            im = Image.open(f).convert("RGB")
            w, h = im.size
            px = im.load()
            # cyan score per column: green and blue well above red, summed down the column
            cols = [sum(max(0, (px[x, y][1] + px[x, y][2]) / 2 - px[x, y][0]) for y in range(h)) / h for x in range(w)]
            best = max(range(w), key=lambda x: cols[x])
            mean = sum(cols) / w
            if cols[best] > 3.2 * mean and cols[best] > 40:
                pts.append([round(i / 24, 3), round(best / (w - 1) - 0.5, 4), round(cols[best], 1)])
    return pts


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    living = encode(LIVING, "venkata-pagadala-living")
    transform = encode(TRANSFORM, "venkata-pagadala-2040")

    still = OUT / "venkata-pagadala-2040.jpg"
    with tempfile.TemporaryDirectory() as tmp:
        last = Path(tmp) / "last.png"
        run("ffmpeg", "-nostdin", "-v", "error", "-sseof", "-0.05", "-i", str(TRANSFORM), "-frames:v", "1", str(last))
        Image.open(last).convert("RGB").resize((800, 800), Image.LANCZOS).save(still, "JPEG", quality=88, optimize=True)

    raw = sweep(TRANSFORM)
    # keep the line's path monotonic left to right: drop points that jump backwards (glints)
    path, lo = [], -1.0
    for t, x, s in raw:
        if x >= lo - 0.01:
            path.append([t, x]); lo = max(lo, x)
    data = {
        "living": living,
        "transform": transform,
        "still2040": {"src": f"{WEB}/{still.name}?v={v(still)}", "width": 800, "height": 800},
        "sweep": path,
    }
    body = (
        "// GENERATED by scripts/hero/export_hero_media.py from the Higgsfield clips in ~/Desktop/Videos/Hero.\n"
        "// Do not edit by hand; rerun the script.\n\n"
        f"export const HERO_PORTRAIT = {json.dumps(data, indent=2)} as const;\n"
    )
    (REPO / "src/data/heroPortrait.ts").write_text(body)
    print(json.dumps({k: data[k] for k in ("living", "transform", "still2040")}, indent=1))
    print(f"sweep: {len(path)} points of {len(raw)} detected; first {path[:1]}, last {path[-1:]}")


if __name__ == "__main__":
    main()
