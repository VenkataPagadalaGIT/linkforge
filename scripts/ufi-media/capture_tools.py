#!/usr/bin/env python3
"""capture_tools.py: screenshots of this site's persona tools for the
User-First Intelligence guide's "try it" cards.

Usage: python3 scripts/ufi-media/capture_tools.py [base_url]
       (default base_url: http://localhost:3411, a `next start` of this repo)

Each page is opened at 1280 px wide in the light theme, and the first 760 px
under the site header is saved as WebP. Writes
public/guides/user-first-intelligence/tools/<slug>.webp and
src/data/ufiToolShots.ts. URLs carry ?v=<md5[:8]> because /public files are
cached for a day.
"""
import asyncio, hashlib, io, json, sys
from pathlib import Path
from PIL import Image
from playwright.async_api import async_playwright

REPO = Path(__file__).resolve().parents[2]
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:3411"
OUT = REPO / "public/guides/user-first-intelligence/tools"
WEB = "/guides/user-first-intelligence/tools"
PAGES = [
    ("personas", "/personas"),
    ("persona-builder", "/personas/builder"),
    ("fanout-journey", "/personas/fanout-journey"),
    ("persona-framework", "/personas/framework"),
]
W, H = 1280, 760


async def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    shots = {}
    async with async_playwright() as p:
        browser = await p.chromium.launch()
        ctx = await browser.new_context(viewport={"width": W, "height": 900}, device_scale_factor=1, color_scheme="light")
        page = await ctx.new_page()
        for slug, path in PAGES:
            await page.goto(BASE + path, wait_until="networkidle")
            await page.wait_for_timeout(1500)
            top = await page.evaluate("(() => { const h = document.querySelector('header, nav'); return h ? Math.ceil(h.getBoundingClientRect().bottom) : 0 })()")
            png = await page.screenshot(clip={"x": 0, "y": top, "width": W, "height": H})
            out = OUT / f"{slug}.webp"
            Image.open(io.BytesIO(png)).convert("RGB").save(out, "WEBP", quality=82, method=6)
            v = hashlib.md5(out.read_bytes()).hexdigest()[:8]
            shots[slug] = {"src": f"{WEB}/{out.name}?v={v}", "width": W, "height": H, "path": path}
            print(f"{slug}: {out.stat().st_size / 1e3:.0f} KB")
        await browser.close()
    (REPO / "src/data/ufiToolShots.ts").write_text(
        "// GENERATED by scripts/ufi-media/capture_tools.py from this site's own pages.\n"
        "// Do not edit by hand; rerun the script against a `next start` of this repo.\n\n"
        f"export const UFI_TOOL_SHOTS = {json.dumps(shots, indent=2)} as const;\n"
    )


if __name__ == "__main__":
    asyncio.run(main())
